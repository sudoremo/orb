/**
 * What each command does, in a line, and the arguments it takes: for the
 * command line's completions and the `?` overlay. Every command has an entry;
 * a test holds the table to `COMMANDS`.
 */
export interface CommandDoc {
  /**
   * What the command palette and the menus call it: `Mark as Read or Unread`.
   * Null for one the palette leaves out — a motion such as `next-message`,
   * which is a key or nothing, or a step of a mode such as `accept-edit`.
   */
  title: string | null;
  /** More words the palette finds it by: `junk` for `spam`. */
  keywords?: string;
  /**
   * What it acts on: the messages the cursor or the selection is on, or the
   * tasks. Refused while the cursor is somewhere else, and greyed out in the
   * palette when there is nothing for it to act on.
   */
  on?: "mail" | "task";
  /** False for one that takes the chat window to mail, tasks or reading, which it does not show. */
  chatWindow?: false;
  /** The arguments, as typed after the name: `<folder>`, `[n]`, `html|text|raw`. */
  args?: string;
  does: string;
}

